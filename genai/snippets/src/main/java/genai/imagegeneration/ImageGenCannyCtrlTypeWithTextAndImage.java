import com.google.cloud.storage.BlobId;
import com.google.cloud.storage.BlobInfo;
import com.google.cloud.storage.Storage;
import com.google.cloud.storage.StorageOptions;
import com.google.genai.Client;
import com.google.genai.types.Blob;
import com.google.genai.types.Candidate;
import com.google.genai.types.Content;
import com.google.genai.types.GenerateContentConfig;
import com.google.genai.types.GenerateContentResponse;
import com.google.genai.types.Part;
import java.util.Optional;

public class ImageGenCannyCtrlTypeWithTextAndImage {

  public static void main(String[] args) {
    // TODO(developer): Replace these variables before running the sample.
    String modelId = "gemini-2.5-flash-image";
    String outputGcsUri = "gs://your-bucket/your-prefix";
    cannyEdgeCustomization(modelId, outputGcsUri);
  }

  // Generates an image using controlled customization with a Canny Edge image and a text prompt.
  public static Optional<String> cannyEdgeCustomization(String modelId, String outputGcsUri) {
    // Client Initialization. Once created, it can be reused for multiple requests.
    try (Client client = Client.builder().location("global").vertexAI(true).build()) {

      GenerateContentConfig config =
          GenerateContentConfig.builder().responseModalities("TEXT", "IMAGE").build();

      GenerateContentResponse response =
          client.models.generateContent(
              modelId,
              Content.fromParts(
                  Part.fromUri(
                      "gs://cloud-samples-data/generative-ai/image/car_canny.png", "image/png"),
                  Part.fromText("a watercolor painting of a red car driving on a road")),
              config);

      byte[] imageBytes =
          response
              .candidates()
              .flatMap(candidates -> candidates.stream().findFirst())
              .flatMap(Candidate::content)
              .flatMap(Content::parts)
              .flatMap(
                  parts ->
                      parts.stream()
                          .filter(part -> part.inlineData().flatMap(Blob::data).isPresent())
                          .findFirst())
              .flatMap(part -> part.inlineData().flatMap(Blob::data))
              .orElseThrow(() -> new IllegalStateException("No image was generated by the model."));

      Storage storage = StorageOptions.getDefaultInstance().getService();
      String gcsPath = outputGcsUri.replace("gs://", "");
      int slashIdx = gcsPath.indexOf('/');
      String bucket = slashIdx > 0 ? gcsPath.substring(0, slashIdx) : gcsPath;
      String objectName =
          slashIdx > 0
              ? gcsPath.substring(slashIdx + 1) + "/canny_customization.png"
              : "canny_customization.png";
      BlobId blobId = BlobId.of(bucket, objectName);
      BlobInfo blobInfo = BlobInfo.newBuilder(blobId).setContentType("image/png").build();
      storage.create(blobInfo, imageBytes);

      String fullGcsUri = String.format("gs://%s/%s", bucket, objectName);
      System.out.println("Generated image URI: " + fullGcsUri);
      return Optional.of(fullGcsUri);
    }
  }
}
